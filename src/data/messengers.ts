export function searchMessengers(
  search: string, 
  selectedProvince: string = 'all',
  sourceList: Messenger[] = MESSENGERS_DATA
): Messenger[] {
  const cleanSearch = search.trim().toLowerCase();
  
  return sourceList.filter((m) => {
    // Province filter
    if (selectedProvince !== 'all') {
      const matchProv = m.provincesList.some(
        (p) => p.toLowerCase() === selectedProvince.toLowerCase()
      ) || m.province.toLowerCase().includes(selectedProvince.toLowerCase());
      if (!matchProv) return false;
    }

    // Text search
    if (!cleanSearch) return true;

    const matchName = m.name.toLowerCase().includes(cleanSearch);
    const matchNickname = m.nickname?.toLowerCase().includes(cleanSearch) || false;
    const matchPhone = m.phone.replace(/[^0-9]/g, '').includes(cleanSearch.replace(/[^0-9]/g, '')) || m.phone.includes(cleanSearch);
    const matchProvince = m.province.toLowerCase().includes(cleanSearch);
    const matchNote = m.note?.toLowerCase().includes(cleanSearch) || false;

    return matchName || matchNickname || matchPhone || matchProvince || matchNote;
  });
}

